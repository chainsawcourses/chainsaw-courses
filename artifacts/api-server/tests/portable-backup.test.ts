import { test } from "node:test";
import assert from "node:assert/strict";
import { portableDataJson, portableManifest, portableRestoreSql } from "../src/lib/portableBackup.ts";

export const fixture = [{
  name: "learners",
  columns: [
    { name: "id", type: "integer", nullable: false, default: null, identity: true },
    { name: "name", type: "text", nullable: false, default: null, identity: false },
    { name: "balance", type: "numeric(30,4)", nullable: true, default: null, identity: false },
    { name: "progress", type: "jsonb", nullable: true, default: null, identity: false },
  ],
  constraints: [{ name: "learners_pkey", definition: "PRIMARY KEY (id)" }],
  rowsJson: `[{"id":42,"name":"O'Brien \\\\ Unicode 漢字","balance":123456789012345678901.1234,"progress":{"completed":true,"score":0,"empty":null}}]`,
}];

test("portable JSON preserves numeric precision and original structured values", () => {
  const output = portableDataJson(fixture, "2026-10-26T22:00:00Z");
  assert.ok(output.includes("123456789012345678901.1234"));
  assert.equal(JSON.parse(output).tables[0].rows[0].progress.completed, true);
});
test("restore uses an isolated schema, one transaction and never drops existing data", () => {
  const sql = portableRestoreSql(fixture);
  assert.match(sql, /CREATE SCHEMA "chainsaw_backup_import"/);
  assert.match(sql, /O''Brien/);
  assert.match(sql, /GENERATED BY DEFAULT AS IDENTITY/);
  assert.match(sql, /setval/);
  assert.match(sql, /BEGIN;/);
  assert.match(sql, /COMMIT;/);
  assert.doesNotMatch(sql, /DROP |TRUNCATE |IF NOT EXISTS/);
});
test("manifest contains byte counts and content checksums", () => {
  const manifest = JSON.parse(portableManifest([{ name: "data.json", bytes: Buffer.from("example") }], "now", 1).toString());
  assert.equal(manifest.files[0].bytes, 7);
  assert.match(manifest.files[0].sha256, /^[a-f0-9]{64}$/);
});
