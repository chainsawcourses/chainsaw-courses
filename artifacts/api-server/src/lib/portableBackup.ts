import { createHash } from "node:crypto";

type Client = { query: (sql: string, params?: unknown[]) => Promise<{ rows: any[] }> };
export type PortableColumn = { name: string; type: string; nullable: boolean; default: string | null; identity: boolean };
const identifier = (value: string) => `"${value.replace(/"/g, '""')}"`;
const literal = (value: string) => "'" + value.replace(/'/g, "''") + "'";

/** PostgreSQL converts values to JSON text itself, preserving bigint/decimal precision. */
export async function capturePortableTables(client: Client, names: readonly string[]): Promise<Array<{
  name: string; columns: PortableColumn[]; constraints: Array<{ name: string; definition: string }>; rowsJson: string;
}>> {
  const tables = [];
  for (const name of names) {
    const columns = await client.query(`
      SELECT a.attname AS name, format_type(a.atttypid,a.atttypmod) AS type,
        NOT a.attnotnull AS nullable, pg_get_expr(d.adbin,d.adrelid) AS default,
        (a.attidentity <> '' OR pg_get_serial_sequence(quote_ident(n.nspname)||'.'||quote_ident(c.relname),a.attname) IS NOT NULL) AS identity,
        tn.nspname AS type_namespace
      FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace
      JOIN pg_type t ON t.oid=a.atttypid JOIN pg_namespace tn ON tn.oid=t.typnamespace
      LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
      WHERE n.nspname='public' AND c.relname=$1 AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum`, [name]);
    if (!columns.rows.length) throw new Error(`Portable export is missing table ${name}`);
    if (columns.rows.some(c => c.type_namespace !== "pg_catalog")) throw new Error(`Portable export needs explicit support for custom types in ${name}`);
    const constraints = await client.query(`
      SELECT conname AS name, pg_get_constraintdef(oid) AS definition FROM pg_constraint
      WHERE conrelid=to_regclass($1) AND contype IN ('p','u','f','c') ORDER BY conname`, [`public.${name}`]);
    const rows = await client.query(`SELECT COALESCE(json_agg(t), '[]'::json)::text AS data FROM public.${identifier(name)} t`);
    tables.push({
      name,
      columns: columns.rows.map(({ type_namespace: _, ...column }) => column as PortableColumn),
      constraints: constraints.rows,
      rowsJson: rows.rows[0].data as string,
    });
  }
  return tables;
}

export function portableRestoreSql(tables: Awaited<ReturnType<typeof capturePortableTables>>, schema = "chainsaw_backup_import"): string {
  const target = identifier(schema);
  // Intentionally no IF NOT EXISTS or DROP: an occupied destination must fail.
  const sql = [
    "-- Import into a NEW recovery schema only. Contains private learner data.",
    "BEGIN;", "SET LOCAL standard_conforming_strings = on;",
    `CREATE SCHEMA ${target};`, `SET LOCAL search_path TO ${target}, pg_catalog;`,
  ];
  for (const table of tables) {
    const columns = table.columns.map(c => `${identifier(c.name)} ${c.type}${
      c.identity ? " GENERATED BY DEFAULT AS IDENTITY" : c.default ? ` DEFAULT ${c.default}` : ""
    }${c.nullable ? "" : " NOT NULL"}`);
    sql.push(`CREATE TABLE ${target}.${identifier(table.name)} (${columns.join(", ")});`);
  }
  for (const table of tables) {
    const name = `${target}.${identifier(table.name)}`;
    sql.push(`INSERT INTO ${name} SELECT * FROM json_populate_recordset(NULL::${name}, ${literal(table.rowsJson)}::json);`);
    for (const column of table.columns.filter(c => c.identity)) {
      sql.push(`SELECT setval(pg_get_serial_sequence(${literal(name)}, ${literal(column.name)}), GREATEST(COALESCE(MAX(${identifier(column.name)}),1),1), COUNT(*)>0) FROM ${name};`);
    }
  }
  // Add referenced keys before foreign keys; rows have already been inserted.
  for (const foreign of [false, true]) for (const table of tables) for (const constraint of table.constraints) {
    if (constraint.definition.startsWith("FOREIGN KEY") !== foreign) continue;
    const definition = constraint.definition.replace(/\bREFERENCES public\./g, `REFERENCES ${target}.`);
    sql.push(`ALTER TABLE ${target}.${identifier(table.name)} ADD CONSTRAINT ${identifier(constraint.name)} ${definition};`);
  }
  sql.push("COMMIT;");
  return sql.join("\n");
}

export function portableDataJson(tables: Awaited<ReturnType<typeof capturePortableTables>>, capturedAt: string): string {
  // Embed original JSON text rather than parsing numbers through JavaScript.
  return `{"format":"chainsaw-portable","version":1,"capturedAt":${JSON.stringify(capturedAt)},"tables":[${tables.map(t =>
    `{"name":${JSON.stringify(t.name)},"columns":${JSON.stringify(t.columns)},"constraints":${JSON.stringify(t.constraints)},"rows":${t.rowsJson}}`,
  ).join(",")}]}`;
}

export function portableManifest(files: Array<{ name: string; bytes: Buffer }>, capturedAt: string, tableCount: number): Buffer {
  return Buffer.from(JSON.stringify({
    format: "chainsaw-portable", version: 1, capturedAt, tableCount,
    databaseConsistency: "repeatable-read snapshot",
    files: files.map(f => ({ name: f.name, bytes: f.bytes.length, sha256: createHash("sha256").update(f.bytes).digest("hex") })),
    limitations: [
      "PDFs and media are in their category folders; download them separately and remap storage references.",
      "Environment secrets, application source code, Firebase-hosted media and external service accounts are not included.",
      "SQL restores table data, column defaults, identities and table constraints into a new recovery schema; application migrations remain the authority for indexes, triggers, roles and permissions.",
      "Export covers the listed application tables, not PostgreSQL system tables or backup job state.",
    ],
  }, null, 2));
}

